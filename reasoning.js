// Разбор ответа модели в формате <размышление>…</размышление><ответ>…</ответ>.
// Гостю уходит только ответ, размышление остаётся для лога. Модуль без побочных эффектов, поэтому тестируется отдельно.

'use strict';

// Убирает размышление из текста. Возвращает { thinking: [строки], body: текст без размышления }.
function stripThinking(raw) {
  const thinking = [];
  const take = (_, t) => { if (t.trim()) thinking.push(t.trim()); return ''; };
  let body = String(raw)
    .replace(/<размышление>([\s\S]*?)<\/размышление>/gi, take)
    // Размышление не закрыто (ответ оборвало по max_tokens): всё после открывающего тега — размышление.
    .replace(/<размышление>([\s\S]*)$/i, take)
    // Модель забыла открывающий тег: всё до закрывающего — размышление.
    .replace(/^([\s\S]*?)<\/размышление>/i, take);
  body = body.replace(/<\/?размышление>/gi, '');
  return { thinking, body: body.trim() };
}

// Достаёт текст из <ответ>…</ответ>. Нет тегов — возвращает текст как есть, без остатков тегов.
// Незакрытый <ответ> (обрыв по max_tokens) берём до конца: лучше неполный ответ, чем никакого.
function pickAnswer(body) {
  const m = /<ответ>([\s\S]*?)(?:<\/ответ>|$)/i.exec(body);
  return (m ? m[1] : body).replace(/<\/?(?:ответ|размышление)>/gi, '').trim();
}

// Тегов в сообщении гостя быть не должно: иначе он мог бы подсунуть модели «готовый» блок ответа.
function stripTags(text) {
  return String(text).replace(/<\/?(?:ответ|размышление)>/gi, '');
}

// Системный промпт для режима без рассуждения (REASONING=off): убираем раздел «ФОРМАТ ОТВЕТА»,
// а из примеров — блоки размышления и теги <ответ>. Остальное (меню, правила, сами примеры) не меняется.
function promptWithoutReasoning(template) {
  return String(template)
    .replace(/^# ФОРМАТ ОТВЕТА\n[\s\S]*?(?=^<примеры>$)/m, '')
    .replace(/^<размышление>\n[\s\S]*?^<\/размышление>\n/gm, '')
    .replace(/^<\/?ответ>\n/gm, '');
}

module.exports = { stripThinking, pickAnswer, stripTags, promptWithoutReasoning };
